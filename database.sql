-- ============================================================
-- MODELO DE VENTAS - SUPABASE / POSTGRESQL
-- ============================================================
-- Basado en los datos reales proporcionados.
--
-- Tablas principales:
--   periodos
--   localidades
--   sucursales
--   supervisores
--   encargados_ventas
--   clientes
--   unidades_negocio
--   divisiones
--   familias
--   marcas
--   calibres
--   productos
--   clasificaciones_marketing
--   ventas
--
-- IMPORTANTE:
-- "Clientes con Compra Totales" NO se almacena en ventas.
-- Se calculará mediante COUNT(DISTINCT id_cliente).
-- ============================================================


BEGIN;


-- ============================================================
-- 1. PERIODOS
-- ============================================================

CREATE TABLE periodos (
    id_periodo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    anio SMALLINT NOT NULL,
    mes SMALLINT NOT NULL,
    nombre_mes VARCHAR(20) NOT NULL,

    CONSTRAINT uq_periodo_anio_mes
        UNIQUE (anio, mes),

    CONSTRAINT chk_periodo_mes
        CHECK (mes BETWEEN 1 AND 12)
);

-- ============================================================
-- 2. LOCALIDADES
-- ============================================================

CREATE TABLE localidades (
    id_localidad INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    nombre VARCHAR(100) NOT NULL,

    CONSTRAINT uq_localidad_nombre
        UNIQUE (nombre)
);


-- ============================================================
-- 3. SUCURSALES
-- ============================================================
-- Actualmente:
-- GLOBAL PACK
--
-- Se mantiene como tabla para permitir agregar futuras sucursales.
-- ============================================================

CREATE TABLE sucursales (
    id_sucursal INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    nombre VARCHAR(150) NOT NULL,

    CONSTRAINT uq_sucursal_nombre
        UNIQUE (nombre)
);


-- ============================================================
-- 4. SUPERVISORES
-- ============================================================
-- Ejemplo:
-- NACUL SOL
--
-- "SIN SUPERVISOR" NO se guarda como persona.
-- En ese caso la FK queda NULL.
-- ============================================================

CREATE TABLE supervisores (
    id_supervisor INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    nombre_completo VARCHAR(150) NOT NULL,

    CONSTRAINT uq_supervisor_nombre
        UNIQUE (nombre_completo)
);


-- ============================================================
-- 5. ENCARGADOS DE VENTA
-- ============================================================
-- En el Excel aparece como:
-- "Sector de Venta"
--
-- Según la explicación del negocio:
-- es el nombre del encargado de ventas.
--
-- Ejemplo:
-- Código 10 -> RODRIGUEZ JORGE GABRIEL
-- ============================================================

CREATE TABLE encargados_ventas (
    id_encargado_venta INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    codigo_sector_venta VARCHAR(50) NOT NULL,
    nombre_completo VARCHAR(150) NOT NULL,

    id_supervisor INTEGER NULL,

    CONSTRAINT uq_encargado_codigo
        UNIQUE (codigo_sector_venta),

    CONSTRAINT fk_encargado_supervisor
        FOREIGN KEY (id_supervisor)
        REFERENCES supervisores(id_supervisor)
        ON UPDATE CASCADE
        ON DELETE SET NULL
);


-- ============================================================
-- 6. CLIENTES
-- ============================================================

CREATE TABLE clientes (
    id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    codigo_cliente VARCHAR(50) NOT NULL,
    razon_social VARCHAR(200) NOT NULL,
    nombre_fantasia VARCHAR(200) NULL,

    id_localidad INTEGER NULL,

    CONSTRAINT uq_cliente_codigo
        UNIQUE (codigo_cliente),

    CONSTRAINT fk_cliente_localidad
        FOREIGN KEY (id_localidad)
        REFERENCES localidades(id_localidad)
        ON UPDATE CASCADE
        ON DELETE SET NULL
);


-- ============================================================
-- 7. UNIDADES DE NEGOCIO
-- ============================================================

CREATE TABLE unidades_negocio (
    id_unidad_negocio INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    nombre VARCHAR(100) NOT NULL,

    CONSTRAINT uq_unidad_negocio_nombre
        UNIQUE (nombre)
);


-- ============================================================
-- 8. DIVISIONES
-- ============================================================

CREATE TABLE divisiones (
    id_division INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_unidad_negocio INTEGER NOT NULL,
    nombre VARCHAR(100) NOT NULL,

    CONSTRAINT uq_division_unidad_nombre
        UNIQUE (id_unidad_negocio, nombre),

    CONSTRAINT fk_division_unidad
        FOREIGN KEY (id_unidad_negocio)
        REFERENCES unidades_negocio(id_unidad_negocio)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);


-- ============================================================
-- 9. FAMILIAS
-- ============================================================

CREATE TABLE familias (
    id_familia INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_division INTEGER NOT NULL,
    nombre VARCHAR(100) NOT NULL,

    CONSTRAINT uq_familia_division_nombre
        UNIQUE (id_division, nombre),

    CONSTRAINT fk_familia_division
        FOREIGN KEY (id_division)
        REFERENCES divisiones(id_division)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);


-- ============================================================
-- 10. MARCAS
-- ============================================================

CREATE TABLE marcas (
    id_marca INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    nombre VARCHAR(100) NOT NULL,

    CONSTRAINT uq_marca_nombre
        UNIQUE (nombre)
);


-- ============================================================
-- 11. CALIBRES
-- ============================================================

CREATE TABLE calibres (
    id_calibre INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    nombre VARCHAR(100) NOT NULL,

    CONSTRAINT uq_calibre_nombre
        UNIQUE (nombre)
);


-- ============================================================
-- 12. PRODUCTOS
-- ============================================================

CREATE TABLE productos (
    id_producto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    codigo_producto VARCHAR(50) NOT NULL,
    nombre VARCHAR(250) NOT NULL,

    id_marca INTEGER NULL,
    id_calibre INTEGER NULL,
    id_familia INTEGER NOT NULL,

    CONSTRAINT uq_producto_codigo
        UNIQUE (codigo_producto),

    CONSTRAINT fk_producto_marca
        FOREIGN KEY (id_marca)
        REFERENCES marcas(id_marca)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT fk_producto_calibre
        FOREIGN KEY (id_calibre)
        REFERENCES calibres(id_calibre)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT fk_producto_familia
        FOREIGN KEY (id_familia)
        REFERENCES familias(id_familia)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);


-- ============================================================
-- 13. CLASIFICACIONES DE MARKETING
-- ============================================================
-- Se guardan como dimensión porque pueden cambiar con el tiempo.
-- La venta apunta a la clasificación usada en ese registro.
-- ============================================================

CREATE TABLE clasificaciones_marketing (
    id_clasificacion_marketing INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    canal_ajustado VARCHAR(100) NULL,
    segmento_mkt VARCHAR(100) NULL,
    canal_mkt VARCHAR(150) NULL,
    subcanal_mkt VARCHAR(150) NULL
);


-- Índice único considerando NULL como vacío.
-- Evita duplicar exactamente la misma clasificación.

CREATE UNIQUE INDEX uq_clasificacion_marketing
ON clasificaciones_marketing (
    COALESCE(canal_ajustado, ''),
    COALESCE(segmento_mkt, ''),
    COALESCE(canal_mkt, ''),
    COALESCE(subcanal_mkt, '')
);


-- ============================================================
-- 14. VENTAS
-- ============================================================
--
-- GRANULARIDAD:
--
-- Una fila representa las ventas agregadas de:
--
--   período
--   cliente
--   sucursal
--   encargado de ventas
--   producto
--   clasificación de marketing
--
-- Las métricas son:
--
--   importe_neto
--   importe_bruto
--   importe_final
--   cantidad_bultos
--   cantidad_hl
-- ============================================================

CREATE TABLE ventas (
    id_venta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_periodo INTEGER NOT NULL,
    id_cliente INTEGER NOT NULL,
    id_sucursal INTEGER NOT NULL,
    id_encargado_venta INTEGER NOT NULL,
    id_producto INTEGER NOT NULL,
    id_clasificacion_marketing INTEGER NULL,

    importe_neto NUMERIC(18,2) NOT NULL DEFAULT 0,
    importe_bruto NUMERIC(18,2) NOT NULL DEFAULT 0,
    importe_final NUMERIC(18,2) NOT NULL DEFAULT 0,

    cantidad_bultos NUMERIC(18,3) NOT NULL DEFAULT 0,
    cantidad_hl NUMERIC(18,6) NOT NULL DEFAULT 0,

    CONSTRAINT fk_venta_periodo
        FOREIGN KEY (id_periodo)
        REFERENCES periodos(id_periodo)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_venta_cliente
        FOREIGN KEY (id_cliente)
        REFERENCES clientes(id_cliente)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_venta_sucursal
        FOREIGN KEY (id_sucursal)
        REFERENCES sucursales(id_sucursal)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_venta_encargado
        FOREIGN KEY (id_encargado_venta)
        REFERENCES encargados_ventas(id_encargado_venta)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_venta_producto
        FOREIGN KEY (id_producto)
        REFERENCES productos(id_producto)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_venta_marketing
        FOREIGN KEY (id_clasificacion_marketing)
        REFERENCES clasificaciones_marketing(id_clasificacion_marketing)
        ON UPDATE CASCADE
        ON DELETE SET NULL
);


-- ============================================================
-- 15. ÍNDICES DE VENTAS
-- ============================================================

CREATE INDEX idx_ventas_periodo
    ON ventas(id_periodo);

CREATE INDEX idx_ventas_cliente
    ON ventas(id_cliente);

CREATE INDEX idx_ventas_sucursal
    ON ventas(id_sucursal);

CREATE INDEX idx_ventas_encargado
    ON ventas(id_encargado_venta);

CREATE INDEX idx_ventas_producto
    ON ventas(id_producto);

CREATE INDEX idx_ventas_marketing
    ON ventas(id_clasificacion_marketing);


-- ============================================================
-- 16. ÍNDICES DE RELACIONES
-- ============================================================

CREATE INDEX idx_clientes_localidad
    ON clientes(id_localidad);

CREATE INDEX idx_productos_familia
    ON productos(id_familia);

CREATE INDEX idx_productos_marca
    ON productos(id_marca);

CREATE INDEX idx_productos_calibre
    ON productos(id_calibre);

CREATE INDEX idx_encargados_supervisor
    ON encargados_ventas(id_supervisor);


COMMIT;

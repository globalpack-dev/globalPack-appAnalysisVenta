INSERT INTO categorias (nombre, id_padre) VALUES
    ('Mercadería',    (SELECT id_categoria FROM categorias WHERE nombre = 'Marketplace')),
    ('Alimentos',     (SELECT id_categoria FROM categorias WHERE nombre = 'Marketplace')),
    ('Yerbas',        (SELECT id_categoria FROM categorias WHERE nombre = 'Marketplace'))
ON CONFLICT (nombre) DO NOTHING;


-- ----------------------------------------------------------------------------
--  3. Las divisiones se asignan a una categoría
-- ----------------------------------------------------------------------------
--  Se agrega la FK a `divisiones` y no a `productos` porque la categoría se
--  deduce de la división: así los 124 productos quedan covered sin tocar
--  ninguno, y un producto nuevo hereda la categoría de su división sola.

ALTER TABLE divisiones ADD COLUMN IF NOT EXISTS id_categoria integer
    REFERENCES categorias(id_categoria);

UPDATE divisiones SET id_categoria = c.id_categoria
FROM categorias c
WHERE c.nombre = CASE
    WHEN divisiones.nombre = 'CERVEZAS'                THEN 'Cervezas'
    WHEN divisiones.nombre = 'GASEOSAS'                THEN 'Gaseosas'
    WHEN divisiones.nombre = 'AGUAS'                   THEN 'Agua y Loft'
    WHEN divisiones.nombre = 'BEBIDAS SABORIZADAS'     THEN 'Agua y Loft'
    WHEN divisiones.nombre = 'ISOTONICAS'              THEN 'Isotónicas'
    WHEN divisiones.nombre = 'BEB ENERGIZANTES'        THEN 'Energizantes'
    WHEN divisiones.nombre = 'VINOS'                   THEN 'Vinos'
    WHEN divisiones.nombre = 'MERCHAND MKTPLACE'       THEN 'Mercadería'
    WHEN divisiones.nombre = 'ALIMENTOS MKTPLACE'      THEN 'Alimentos'
    WHEN divisiones.nombre = 'YERBAS MARKETPLACE'      THEN 'Yerbas'
END;

-- La categoría "Marketplace" no tiene división propia: agrupa las tres. Por eso
-- NO aparece en el UPDATE de arriba.


-- ----------------------------------------------------------------------------
--  4. RLS
-- ----------------------------------------------------------------------------
--  Mismas reglas que el resto de las tablas de negocio: lectura para los dos
--  roles, escritura para los dos, DELETE sólo admin.
-- ----------------------------------------------------------------------------

ALTER TABLE categorias ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS categorias_select ON categorias;
CREATE POLICY categorias_select ON categorias
    FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS categorias_insert ON categorias;
CREATE POLICY categorias_insert ON categorias
    FOR INSERT TO authenticated WITH CHECK (true);

DROP POLICY IF EXISTS categorias_update ON categorias;
CREATE POLICY categorias_update ON categorias
    FOR UPDATE TO authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS categorias_delete ON categorias;
CREATE POLICY categorias_delete ON categorias
    FOR DELETE TO authenticated
    USING (
        EXISTS (SELECT 1 FROM empleados e WHERE e.id = auth.uid() AND e.rol = 'admin')
    );


-- ----------------------------------------------------------------------------
--  5. fn_ventas_filtradas — acepta p_categoria
-- ----------------------------------------------------------------------------
--  La categoría se filtra por división, que es donde vive. Se acepta el
--  nombre de la categoría (incluido "Marketplace", que trae las tres partes)
--  o el de una subcategoría.
--
--  IMPORTANTE: firma nueva, así que hace falta DROP previo o la función queda
--  sobrecargada y Postgres rechaza las llamadas. Ver ESTADO.md.

DROP FUNCTION IF EXISTS public.fn_ventas_filtradas(
    integer, integer, integer, integer, integer, integer, text, integer
);


CREATE OR REPLACE FUNCTION fn_ventas_filtradas(
    p_anio            int  DEFAULT NULL,
    p_mes             int  DEFAULT NULL,
    p_cliente         int  DEFAULT NULL,
    p_localidad       int  DEFAULT NULL,
    p_marca           int  DEFAULT NULL,
    p_encargado       int  DEFAULT NULL,
    p_canal           text DEFAULT NULL,
    p_unidad_negocio  int  DEFAULT NULL,
    p_categoria       text DEFAULT NULL
)
RETURNS SETOF v_ventas_detalle
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = public
AS $$
    SELECT d.*
    FROM v_ventas_detalle d
    JOIN clientes c ON c.id_cliente = d.id_cliente
    WHERE (p_anio      IS NULL OR d.anio = p_anio)
      AND (p_mes       IS NULL OR d.mes = p_mes)
      AND (p_cliente   IS NULL OR d.id_cliente = p_cliente)
      AND (p_localidad IS NULL OR c.id_localidad = p_localidad)
      AND (p_marca     IS NULL OR d.id_producto IN (
              SELECT pr.id_producto FROM productos pr WHERE pr.id_marca = p_marca))
      AND (p_encargado IS NULL OR d.id_encargado_venta = p_encargado)
      AND (p_canal     IS NULL OR d.canal_ajustado = p_canal)
      AND (
          p_unidad_negocio IS NULL
          OR EXISTS (
              SELECT 1
              FROM productos pr2
              LEFT JOIN divisiones d2 ON d2.id_division = pr2.id_division
              WHERE pr2.id_producto = d.id_producto
                AND d2.id_unidad_negocio = p_unidad_negocio
          )
      )
      AND (
          p_categoria IS NULL
          -- Comparación por texto porque el filtro manda el nombre que ve el
          -- usuario, no un id. El `<select>` arma la lista desde
          -- `categorias`, así que el casing coincide.
          -- `cat.nombre = ... OR padre.nombre = ...`: por la segunda parte,
          -- elegir "Marketplace" trae Mercadería, Alimentos y Yerbas.
          OR EXISTS (
              SELECT 1
              FROM productos pr3
              JOIN divisiones d3   ON d3.id_division  = pr3.id_division
              JOIN categorias cat ON cat.id_categoria = d3.id_categoria
              LEFT JOIN categorias padre ON padre.id_categoria = cat.id_padre
              WHERE pr3.id_producto = d.id_producto
                AND (cat.nombre = p_categoria OR padre.nombre = p_categoria)
          )
      );
$$;


-- ----------------------------------------------------------------------------
--  6. La categoría se agrega a la vista
-- ----------------------------------------------------------------------------
--  Para que las páginas la muestren sin un JOIN extra.
--
--  NO hace falta DROP VIEW. CREATE OR REPLACE VIEW sólo exige que las columnas
--  existentes se mantengan en el mismo orden y tipo; AGREGAR columnas al final
--  está permitido. El DROP además era peligroso: de esta vista dependen 15
--  funciones, asi que DROP VIEW sin CASCADE falla y con CASCADE se lleva las 15.
--
--  Por eso las columnas nuevas van al final y las 33 viejas quedan intactas.


CREATE OR REPLACE VIEW v_ventas_detalle AS
SELECT
    v.id_venta,
    v.id_periodo,
    v.id_cliente,
    v.id_sucursal,
    v.id_encargado_venta,
    v.id_producto,
    v.id_clasificacion_marketing,

    p.anio,
    p.mes,
    p.nombre_mes,
    p.nombre_mes || ' ' || p.anio::text AS periodo_label,

    c.codigo_cliente,
    COALESCE(c.nombre_fantasia, c.razon_social) AS cliente_nombre,

    su.nombre AS sucursal_nombre,

    ev.codigo_sector_venta,
    ev.nombre_completo AS encargado_nombre,

    sv.nombre_completo AS supervisor_nombre,

    pr.codigo_producto,
    pr.nombre AS producto_nombre,
    m.nombre AS marca_nombre,
    f.nombre AS familia_nombre,
    d.nombre AS division_nombre,
    un.nombre AS unidad_negocio_nombre,
    cal.nombre AS calibre_nombre,

    cm.canal_ajustado,
    cm.segmento_mkt,
    cm.canal_mkt,
    cm.subcanal_mkt,

    v.importe_neto,
    v.importe_bruto,
    v.importe_final,
    v.cantidad_bultos,
    v.cantidad_hl,

    -- Nuevas, al final para no romper el tipo de retorno:
    cat.nombre AS categoria_nombre,
    cat.id_categoria
FROM ventas v
JOIN periodos p        ON p.id_periodo = v.id_periodo
JOIN clientes c        ON c.id_cliente = v.id_cliente
JOIN sucursales su     ON su.id_sucursal = v.id_sucursal
JOIN encargados_ventas ev ON ev.id_encargado_venta = v.id_encargado_venta
LEFT JOIN supervisores sv ON sv.id_supervisor = ev.id_supervisor
JOIN productos pr      ON pr.id_producto = v.id_producto
LEFT JOIN marcas m     ON m.id_marca = pr.id_marca
JOIN familias f        ON f.id_familia = pr.id_familia
LEFT JOIN divisiones d ON d.id_division = pr.id_division
LEFT JOIN unidades_negocio un ON un.id_unidad_negocio = d.id_unidad_negocio
LEFT JOIN categorias cat ON cat.id_categoria = d.id_categoria
LEFT JOIN calibres cal ON cal.id_calibre = pr.id_calibre
LEFT JOIN clasificaciones_marketing cm
    ON cm.id_clasificacion_marketing = v.id_clasificacion_marketing;


-- ----------------------------------------------------------------------------
--  7. fn_categorias — alimenta el <select> de Categoría
-- ----------------------------------------------------------------------------
--  Devuelve las categorías con su padre, para que el menú muestre "Marketplace"
--  arriba y sus tres partes (Mercadería / Alimentos / Yerbas) debajo. El filtro
--  acepta cualquiera de los dos niveles: ver el EXISTS de p_categoria en
--  fn_ventas_filtradas.

CREATE OR REPLACE FUNCTION fn_categorias()
RETURNS TABLE (
    nombre   text,
    id_padre text
)
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = public
AS $$
    SELECT c.nombre, p.nombre
    FROM categorias c
    LEFT JOIN categorias p ON p.id_categoria = c.id_padre
    ORDER BY c.id_padre NULLS FIRST, c.id_categoria;
$$;



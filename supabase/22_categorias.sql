-- ============================================================================
--  Categorías de producto
--
--  Por qué: el filtro de Ventas tiene Período, Marca, Sector y Canal, y falta
--  "Categoría" (gaseosas, alcohol, agua, etc.). No se puede filtrar por
--  `familias` porque esa columna no sirve: en el Excel real una familia
--  aparece en hasta 8 divisiones distintas ("REGULAR" está en GASEOSAS,
--  CERVEZAS, VINOS...). Ver 15_division_en_producto.sql.
--
--  Se hace una tabla propia y no un `CASE` dentro de la función porque el
--  agrupamiento es una decisión comercial, no una regla técnica:
--  "Agua y Loft" junta agua con bebidas sabORIZadas, que no son lo mismo, y
--  eso no debería quedar metido en un string dentro de una función SQL.
--
--  Marketplace agrupa tres divisiones (mercadería, alimentos y yerbas) pero
--  también se puede filtrar cada parte por separado: por eso la relación
--  `categorias.id` ← `divisiones.id_categoria` es 1 a N.
--
--  Los 124 productos quedan covered: 41 + 29 + 16 + 12 + 10 + 1 + 15 = 124.
--
--  Ejecutar en el SQL Editor de supabase.com.
-- ============================================================================


-- ----------------------------------------------------------------------------
--  1. Tabla de categorías
-- ----------------------------------------------------------------------------
--  `nombre` es UNIQUE: el filtro manda el nombre y no un id, porque "Agua y
--  Loft" es lo que el usuario ve. El id queda para joins y orden.

CREATE TABLE IF NOT EXISTS categorias (
    id_categoria INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(60) NOT NULL,
    -- Para las subcategorías de Marketplace. NULL en las categorías de primer
    -- nivel.
    id_padre      INTEGER REFERENCES categorias(id_categoria),

    CONSTRAINT uq_categoria_nombre UNIQUE (nombre),
    CONSTRAINT fk_categoria_padre
        FOREIGN KEY (id_padre)
        REFERENCES categorias(id_categoria)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT ck_categoria_no_es_propia_padre
        CHECK (id_padre IS NULL OR id_padre <> id_categoria)
);



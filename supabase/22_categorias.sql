-- Las 10 categorías con su padre
SELECT c.nombre, p.nombre AS padre
FROM categorias c LEFT JOIN categorias p ON p.id_categoria = c.id_padre
ORDER BY c.id_padre NULLS FIRST, c.id_categoria;

-- Las 10 divisiones con su categoría
SELECT d.nombre AS division, c.nombre AS categoria
FROM divisiones d LEFT JOIN categorias c ON c.id_categoria = d.id_categoria
ORDER BY c.nombre, d.nombre;

-- Ninguna división sin categoría
SELECT COUNT(*) AS divisiones_sin_categoria
FROM divisiones WHERE id_categoria IS NULL;

-- Los 124 productos, todos con categoría
SELECT cat.nombre AS categoria, COUNT(pr.id_producto) AS productos
FROM productos pr
JOIN divisiones d   ON d.id_division = pr.id_division
LEFT JOIN categorias cat ON cat.id_categoria = d.id_categoria
GROUP BY cat.nombre ORDER BY cat.nombre;

-- Marketplace trae las tres (15 productos)
SELECT cat.nombre, p.nombre AS padre, COUNT(*) AS productos
FROM productos pr
JOIN divisiones d      ON d.id_division = pr.id_division
JOIN categorias cat    ON cat.id_categoria = d.id_categoria
LEFT JOIN categorias p ON p.id_categoria = cat.id_padre
WHERE p.nombre = 'Marketplace'
GROUP BY cat.nombre, p.nombre;

